test('monthly forecasts clamp short months without drifting, never count receipts twice and do not backfill old flags', () => {
  assert.equal(monthlyDate(2028,1,31),'2028-02-29');
  assert.equal(monthlyDate(2027,1,31),'2027-02-28');
  const source = {id:'source',description:'Salário',amount:3000,date:'2026-10-31',recurring:true};
  assert.deepEqual(incomeForecasts([source],2026,10),[]);
  source.income_schedule = makeIncomeSchedule(source,'2026-11-02');
  assert.equal(source.income_schedule.start,'2026-12-31');
  assert.equal(incomeForecasts([source],2026,10).length,0);
  assert.equal(incomeForecasts([source],2026,11)[0].due,'2026-12-31');
  assert.equal(incomeForecasts([source],2027,1)[0].due,'2027-02-28');
  assert.equal(incomeForecasts([source],2027,2)[0].due,'2027-03-31');
  assert.equal(incomeForecasts([source,{recurrence_source:'source',recurrence_due:'2027-02-28',date:'2027-03-01'}],2027,1).length,0);
  assert.equal(incomeForecasts([source,{recurrence_source:'source',recurrence_due:'2027-03-05',date:'2027-03-05'}],2027,2).length,0,'changing the scheduled day does not duplicate a month');
  source.income_schedule.end='2027-02-15';
  assert.equal(incomeForecasts([source],2027,1).length,0);
  source.income_schedule.active=false;
  assert.equal(incomeForecasts([source],2026,11).length,0);
  assert.equal(validIncomeSchedule({...source.income_schedule,start:'2026-02-31'}),false);
});

test('confirm recurring income validates ownership, due day, consent snapshot, atomic retries, backups and stopping',async()=>{
  const db=new PGlite(),alice='00000000-0000-0000-0000-000000000001',bob='00000000-0000-0000-0000-000000000002';
  try {
    await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as 'select nullif(current_setting(''request.jwt.claim.sub'',true),'''')::uuid';
      grant usage on schema auth to authenticated,anon;grant execute on function auth.uid() to authenticated,anon;
      insert into auth.users values('${alice}'),('${bob}');`);
    const dir=new URL('../supabase/migrations/',import.meta.url);
    for(const file of (await readdir(dir)).filter(f=>f.endsWith('.sql')).sort()) await db.exec(await readFile(new URL(file,dir),'utf8'));
    await db.exec(`set role authenticated;set request.jwt.claim.sub='${alice}';`);
    const schedule={active:true,start:'2020-02-01',end:'',day:31,amount:3000,description:'Salário mensal',category:'salário',notes:''};
    const source=(await db.query(`insert into public.vault_records(entity,data) values('Income',$1) returning *`,[JSON.stringify({description:'Salário original',amount:2900,date:'2020-01-31',recurring:true,income_schedule:schedule})])).rows[0];
    const confirm=(due='2020-02-29',amount=2999.99,date='2020-03-01',snapshot=schedule)=>db.query('select public.confirm_recurring_income($1,$2,$3,$4,$5) as result',[source.id,due,amount,date,JSON.stringify(snapshot)]);
    assert.equal((await db.query("select count(*)::int as n from public.vault_records where entity='Income'")).rows[0].n,1,'forecasts do not create financial rows');
    await assert.rejects(confirm('2020-02-28'));
    await assert.rejects(confirm('2020-02-29',0));
    await assert.rejects(confirm('2020-02-29',10.001));
    await assert.rejects(confirm('2099-01-31'));
    await assert.rejects(confirm('2020-02-29',10,'2099-01-01'));
    await assert.rejects(confirm('2020-02-29',10,'2020-03-01',{...schedule,amount:1}));
    await db.exec(`set request.jwt.claim.sub='${bob}';`); await assert.rejects(confirm());
    assert.equal((await db.query("select count(*)::int as n from public.vault_records where entity='Income'")).rows[0].n,0);
    await db.exec(`set request.jwt.claim.sub='${alice}';`);
    const results=await Promise.all([confirm(),confirm()]);
    assert.equal(results.filter(r=>r.rows[0].result.alreadyReceived===false).length,1);
    const received=(await db.query("select * from public.vault_records where data ? 'recurrence_source'")).rows[0];
    assert.equal(received.data.amount,2999.99);assert.equal(received.data.date,'2020-03-01');
    assert.equal(received.data.recurring,false);assert.equal(received.data.recurrence_due,'2020-02-29');
    assert.equal((await db.query('select data from public.vault_records where id=$1',[source.id])).rows[0].data.amount,2900);
    await assert.rejects(db.query("insert into public.vault_records(entity,data) values('Income',$1)",[JSON.stringify(received.data)]));
    await db.query("select public.patch_vault_record($1,'Income',$2)",[source.id,JSON.stringify({income_schedule:{...schedule,active:false},recurring:false})]);
    await assert.rejects(confirm('2020-03-31'));
    assert.equal((await confirm()).rows[0].result.alreadyReceived,true,'receipt retry is safe after stopping');
    assert.equal((await confirm('2020-02-15')).rows[0].result.alreadyReceived,true,'the month stays received even if the due day changes');
    const rows=(await db.query('select * from public.vault_records')).rows;
    const backup=await buildBackup(async entity=>rows.filter(r=>r.entity===entity).map(r=>({id:r.id,...r.data})),alice,{});
    const imported=await prepareImport(backup,bob);
    const child=imported.find(r=>r.data.recurrence_source),parent=imported.find(r=>r.data.income_schedule);
    assert.equal(child.data.recurrence_source,parent.id);
    await db.exec(`set request.jwt.claim.sub='${bob}';`);
    const importResult=await db.query('select public.import_vault_backup($1,$2) as result',[JSON.stringify(imported),bob]);
    assert.equal(importResult.rows[0].result.addedTotal,2);
    await db.exec(`set request.jwt.claim.sub='${alice}';`);
    await db.query('select public.delete_income_with_recurrence($1)',[source.id]);
    const remaining=(await db.query("select data from public.vault_records where entity='Income'")).rows;
    assert.equal(remaining.length,1);assert.equal(remaining[0].data.amount,2999.99);assert.equal(remaining[0].data.recurrence_source,undefined);
    await db.exec('reset role;set role anon;');await assert.rejects(confirm());
  } finally {await db.close();}
});
